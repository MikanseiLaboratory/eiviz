using System.ComponentModel;
using System.Globalization;
using System.Windows.Data;

namespace Eiviz.Host.I18n;

public static class Loc
{
    public static LocSource Source { get; } = new();

    internal static AppLanguage Language { get; private set; } = AppPrefs.Current.Language;

    public static string T(string key)
    {
        var table = Language == AppLanguage.Ja ? Ja : En;
        if (table.TryGetValue(key, out var value))
            return value;
        return En.TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string Format(string key, params object[] args) =>
        string.Format(CultureInfo.CurrentCulture, T(key), args);

    public static string Error(string actionKey, int code)
    {
        var key = actionKey.StartsWith("action.", StringComparison.Ordinal) ? actionKey : $"action.{actionKey}";
        var action = T(key);
        var bare = key["action.".Length..];
        var reason = (bare, code) switch
        {
            ("Load session" or "Save session" or "Export session", 3 or -1 or -3) => T("error.badSession"),
            ("Save session", 2) => T("error.noSessionFile"),
            ("Load session" or "Export session", 5 or -5) => T("error.io"),
            (_, 1) => T("error.alreadyCreated"),
            (_, 2) => T("error.notCreated"),
            (_, 3) => T("error.invalidArgument"),
            (_, 4) => T("error.device"),
            (_, 5) => T("error.io"),
            (_, -1) => T("error.badSession"),
            _ => Format("error.unknown", code)
        };
        return Format("error.format", action, reason);
    }

    public static string MissingFile(string actionKey)
    {
        var key = actionKey.StartsWith("action.", StringComparison.Ordinal) ? actionKey : $"action.{actionKey}";
        return Format("error.format", T(key), T("error.missingFile"));
    }

    internal static void Apply(AppLanguage language)
    {
        Language = language;
        Source.Refresh();
    }

    public sealed class LocSource : INotifyPropertyChanged
    {
        public event PropertyChangedEventHandler? PropertyChanged;

        public string this[string key] => T(key);

        public void Refresh() =>
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(Binding.IndexerName));
    }

